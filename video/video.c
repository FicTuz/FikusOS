static const unsigned char glyph_yo_cap[8] = {0x3C,0x18,0x7E,0x60,0x7C,0x60,0x7E,0x00};
static const unsigned char glyph_yo_low[8] = {0x00,0x18,0x3C,0x66,0x7E,0x60,0x3C,0x00};
static const unsigned char glyph_unknown[8] = {0xFF,0x81,0x81,0x81,0x81,0x81,0x81,0xFF};

const unsigned char *video_glyph(unsigned int cp)
{
    if (cp >= 0x20 && cp <= 0x7F) return font_ascii[cp - 0x20];
    if (cp == 0x0401) return glyph_yo_cap;
    if (cp == 0x0451) return glyph_yo_low;
    if (cp >= 0x0410 && cp <= 0x044F) return font_cyr[cp - 0x0410];
    return glyph_unknown;
}

/* =========================================================
 *  putchar_xy — 1 символ в (x, y), курсор не трогает
 * ========================================================= */
void putchar_xy(int x, int y, unsigned int cp, unsigned char color)
{
    int px = x * CHAR_W;
    int py = y * CHAR_H;

    unsigned char fg = color & 0x0F;
    unsigned char bg = (color >> 4) & 0x0F;

    const unsigned char *glyph = video_glyph(cp);

    for (int row = 0; row < CHAR_H; row++) {
        unsigned char bits = glyph[row];
        for (int col = 0; col < CHAR_W; col++) {
            unsigned char pixel_color = (bits & (0x80 >> col)) ? fg : bg;
            buf_putpixel(px + col, py + row, pixel_color);
        }
    }
}

/* =========================================================
 *  printB_xy — большой символ с масштабом (scale 1..8)
 * ========================================================= */
void printB_xy(int x, int y, const char *s, unsigned char color, int scale)
{
    if (!s) return;
    if (scale < 1) scale = 1;
    if (scale > 8) scale = 8;

    unsigned char fg = color & 0x0F;
    unsigned char bg = (color >> 4) & 0x0F;

    int cx = x;
    int cy = y;

    while (*s) {
        unsigned char c = (unsigned char)*s;

        if (c == '\n') {
            cy += CHAR_H * scale;
            cx = x;
            s++;
            continue;
        }

        const unsigned char *glyph = video_glyph(c);

        /* Рисуем глиф, растянутый в scale раз */
        for (int row = 0; row < CHAR_H; row++) {
            unsigned char bits = glyph[row];
            for (int col = 0; col < CHAR_W; col++) {
                unsigned char pixel_color = (bits & (0x80 >> col)) ? fg : bg;

                /* Закрашиваем блок scale×scale */
                for (int dy = 0; dy < scale; dy++) {
                    for (int dx = 0; dx < scale; dx++) {
                        int px = cx + col * scale + dx;
                        int py = cy + row * scale + dy;
                        buf_putpixel(px, py, pixel_color);
                    }
                }
            }
        }

        cx += CHAR_W * scale;
        s++;
    }
}

/* printB — вывод с текущего курсора, обновляет его */
void printB(const char *s, unsigned char color, int scale)
{
    int x, y;
    video_get_cursor(&x, &y);

    printB_xy(x, y, s, color, scale);

    /* Обновить курсор — но «в символах», а не в пикселях.
       Считаем сколько символов * scale пикселей по ширине. */
    if (!s) { video_flush(); return; }

    if (scale < 1) scale = 1;
    if (scale > 8) scale = 8;

    int len = 0;
    const char *p = s;
    while (*p) {
        if (*p == '\n') {
            y += (CHAR_H / CHAR_H) * scale;
            x = 0;
        } else {
            len++;
        }
        p++;
    }

    /* Пересчёт в символьные координаты */
    int advance = (len * CHAR_W * scale) / CHAR_W;
    x += advance;

    /* Если ушли за границу — переносим */
    if (x >= COLS) {
        x = 0;
        y += scale;
    }
    if (y >= ROWS) y = ROWS - 1;

    video_set_cursor(x, y);
    video_flush();
}

/* =========================================================
 *  Курсор
 * ========================================================= */
static int cursor_x = 0;
static int cursor_y = 0;

void video_set_cursor(int x, int y) { cursor_x = x; cursor_y = y; }
void video_get_cursor(int *x, int *y) { if (x) *x = cursor_x; if (y) *y = cursor_y; }

/* =========================================================
 *  UTF-8 декодер
 * ========================================================= */
static unsigned int utf8_decode(const unsigned char *s, int *advance)
{
    unsigned char b0 = s[0];
    if (b0 < 0x80) { *advance = 1; return b0; }
    if ((b0 & 0xE0) == 0xC0) {
        if ((s[1] & 0xC0) != 0x80) { *advance = 1; return 0xFFFD; }
        *advance = 2;
        return ((unsigned int)(b0 & 0x1F) << 6) | (s[1] & 0x3F);
    }
    if ((b0 & 0xF0) == 0xE0) {
        if ((s[1] & 0xC0) != 0x80 || (s[2] & 0xC0) != 0x80) {
            *advance = 1; return 0xFFFD;
        }
        *advance = 3;
        return ((unsigned int)(b0 & 0x0F) << 12) |
               ((unsigned int)(s[1] & 0x3F) << 6) |
               ((unsigned int)(s[2] & 0x3F));
    }
    if ((b0 & 0xF8) == 0xF0) {
        if ((s[1] & 0xC0) != 0x80 || (s[2] & 0xC0) != 0x80 ||
            (s[3] & 0xC0) != 0x80) {
            *advance = 1; return 0xFFFD;
        }
        *advance = 4;
        return ((unsigned int)(b0 & 0x07) << 18) |
               ((unsigned int)(s[1] & 0x3F) << 12) |
               ((unsigned int)(s[2] & 0x3F) << 6) |
               ((unsigned int)(s[3] & 0x3F));
    }
    *advance = 1;
    return 0xFFFD;
}

/* =========================================================
 *  video_scroll_up — сдвиг вверх на 8 пикселей
 * ========================================================= */
void video_scroll_up(unsigned char bg_color)
{
    unsigned int row_bytes = 80 * 8;

    for (int p = 0; p < 4; p++) {
        unsigned char *plane = &back_buffer[p * VGA_PLANE_SIZE];
        for (unsigned int i = 0; i < VGA_PLANE_SIZE - row_bytes; i++)
            plane[i] = plane[i + row_bytes];

        unsigned char fill = (bg_color & (1 << p)) ? 0xFF : 0x00;
        for (unsigned int i = VGA_PLANE_SIZE - row_bytes; i < VGA_PLANE_SIZE; i++)
            plane[i] = fill;
    }
}

/* =========================================================
 *  putchar
 * ========================================================= */
void putchar(char c, unsigned char color)
{
    if (c == '\n') {
        cursor_x = 0;
        cursor_y++;
        if (cursor_y >= ROWS) { video_scroll_up(color >> 4); cursor_y = ROWS - 1; }
        return;
    }
    if (c == '\r') { cursor_x = 0; return; }
    if (c == '\b') {
        if (cursor_x > 0) {
            cursor_x--;
            putchar_xy(cursor_x, cursor_y, ' ', color);
        }
        return;
    }
    if (c == '\t') {
        cursor_x = (cursor_x + 8) & ~7;
        if (cursor_x >= COLS) { cursor_x = 0; cursor_y++; }
        return;
    }

    putchar_xy(cursor_x, cursor_y, (unsigned int)(unsigned char)c, color);

    cursor_x++;
    if (cursor_x >= COLS) {
        cursor_x = 0;
        cursor_y++;
        if (cursor_y >= ROWS) { video_scroll_up(color >> 4); cursor_y = ROWS - 1; }
    }
}

/* =========================================================
 *  print
 * ========================================================= */
void print(const char *s, unsigned char color)
{
    if (!s) return;

    int guard = 0;
    while (*s) {
        int adv = 1;
        unsigned int cp = utf8_decode((const unsigned char *)s, &adv);
        s += adv;

        if (cp == '\n') {
            cursor_x = 0;
            cursor_y++;
            if (cursor_y >= ROWS) { video_scroll_up(color >> 4); cursor_y = ROWS - 1; }
            continue;
        }
        if (cp == '\r') { cursor_x = 0; continue; }
        if (cp == '\b') {
            if (cursor_x > 0) {
                cursor_x--;
                putchar_xy(cursor_x, cursor_y, ' ', color);
            }
            continue;
        }
        if (cp == '\t') {
            cursor_x = (cursor_x + 8) & ~7;
            if (cursor_x >= COLS) { cursor_x = 0; cursor_y++; }
            continue;
        }

        putchar_xy(cursor_x, cursor_y, cp, color);

        cursor_x++;
        if (cursor_x >= COLS) {
            cursor_x = 0;
            cursor_y++;
            if (cursor_y >= ROWS) { video_scroll_up(color >> 4); cursor_y = ROWS - 1; }
        }

        guard++;
        if (guard > 8192) break;
    }
    video_flush();
}

/* =========================================================
 *  print_xy
 * ========================================================= */
void print_xy(int x, int y, const char *s, unsigned char color)
{
    if (!s) return;

    int cx = x, cy = y;
    int guard = 0;

    while (*s) {
        int adv = 1;
        unsigned int cp = utf8_decode((const unsigned char *)s, &adv);
        s += adv;

        if (cp == '\n') { cy++; cx = x; continue; }
        if (cp == '\r') { cx = x; continue; }

        putchar_xy(cx, cy, cp, color);
        cx++;
        if (cx >= COLS) { cx = x; cy++; }

        guard++;
        if (guard > 8192) break;
    }
    video_flush();
}

/* =========================================================
 *  print_int / print_hex / print_bin
 * ========================================================= */
void print_int(int v, unsigned char color)
{
    char buf[16];
    char tmp[16];
    int i = 0;
    int neg = 0;

    if (v < 0) { neg = 1; v = -v; }

    if (v == 0) {
        putchar('0', color);
        video_flush();
        return;
    }

    while (v > 0 && i < 15) { tmp[i++] = (char)('0' + (v % 10)); v /= 10; }
    if (neg) tmp[i++] = '-';

    int n = 0;
    while (i > 0) buf[n++] = tmp[--i];
    buf[n] = 0;

    print(buf, color);
}

void print_hex(unsigned int v, unsigned char color)
{
    char buf[16];
    const char *hex = "0123456789ABCDEF";
    char tmp[16];
    int i = 0;

    buf[0] = '0'; buf[1] = 'x';

    if (v == 0) { buf[2] = '0'; buf[3] = 0; print(buf, color); return; }

    while (v > 0 && i < 15) { tmp[i++] = hex[v & 0xF]; v >>= 4; }

    int n = 2;
    while (i > 0) buf[n++] = tmp[--i];
    buf[n] = 0;
    print(buf, color);
}

void print_bin(unsigned int v, unsigned char color)
{
    char buf[40];
    char tmp[40];
    int i = 0;

    buf[0] = '0'; buf[1] = 'b';

    if (v == 0) { buf[2] = '0'; buf[3] = 0; print(buf, color); return; }

    while (v > 0 && i < 38) { tmp[i++] = (char)('0' + (v & 1)); v >>= 1; }

    int n = 2;
    while (i > 0) buf[n++] = tmp[--i];
    buf[n] = 0;
    print(buf, color);
}

/* =========================================================
 *  video_clear
 * ========================================================= */
void video_clear(unsigned char color)
{
    unsigned char bg = (color >> 4) & 0x0F;

    for (int p = 0; p < 4; p++) {
        unsigned char fill = (bg & (1 << p)) ? 0xFF : 0x00;
        unsigned char *plane = &back_buffer[p * VGA_PLANE_SIZE];
        for (unsigned int i = 0; i < VGA_PLANE_SIZE; i++)
            plane[i] = fill;
    }

    cursor_x = 0;
    cursor_y = 0;

    video_flush();
}

/* =========================================================
 *  video_fill
 * ========================================================= */
void video_fill(int x, int y, int w, int h, unsigned char color)
{
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++)
            buf_putpixel(x + i, y + j, color & 0x0F);
}

/* =========================================================
 *  video_hline / video_vline
 * ========================================================= */
void video_hline(int x, int y, int w, unsigned char color)
{
    for (int i = 0; i < w; i++) buf_putpixel(x + i, y, color);
}

void video_vline(int x, int y, int h, unsigned char color)
{
    for (int i = 0; i < h; i++) buf_putpixel(x, y + i, color);
}

/* =========================================================
 *  video_rect — рамка (не заливка)
 * ========================================================= */
void video_rect(int x, int y, int w, int h, unsigned char color)
{
    video_hline(x, y, w, color);
    video_hline(x, y + h - 1, w, color);
    video_vline(x, y, h, color);
    video_vline(x + w - 1, y, h, color);
}

/* =========================================================
 *  video_box3d — Win95-подобная рамка
 *  raised=1 → выпуклая, raised=0 → вдавленная
 * ========================================================= */
void video_box3d(int x, int y, int w, int h,
                 unsigned char light, unsigned char face, unsigned char shadow,
                 int raised)
{
    unsigned char tl = raised ? light  : shadow;
    unsigned char br = raised ? shadow : light;

    (void)face;

    video_hline(x, y, w - 1, tl);
    video_vline(x, y, h - 1, tl);
    video_hline(x + 1, y + h - 1, w - 1, br);
    video_vline(x + w - 1, y + 1, h - 1, br);
}

/* =========================================================
 *  video_line — линия Брезенхема
 * ========================================================= */
void video_line(int x0, int y0, int x1, int y1, unsigned char color)
{
    int dx = (x1 > x0) ? (x1 - x0) : (x0 - x1);
    int dy = (y1 > y0) ? (y1 - y0) : (y0 - y1);
    int sx = (x0 < x1) ? 1 : -1;
    int sy = (y0 < y1) ? 1 : -1;
    int err = dx - dy;

    for (;;) {
        buf_putpixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 <  dx) { err += dx; y0 += sy; }
    }
}

/* =========================================================
 *  video_circle — окружность Брезенхема
 * ========================================================= */
void video_circle(int cx, int cy, int r, unsigned char color)
{
    int x = r;
    int y = 0;
    int err = 1 - r;

    while (x >= y) {
        buf_putpixel(cx + x, cy + y, color);
        buf_putpixel(cx + y, cy + x, color);
        buf_putpixel(cx - y, cy + x, color);
        buf_putpixel(cx - x, cy + y, color);
        buf_putpixel(cx - x, cy - y, color);
        buf_putpixel(cx - y, cy - x, color);
        buf_putpixel(cx + y, cy - x, color);
        buf_putpixel(cx + x, cy - y, color);

        y++;
        if (err < 0) {
            err += 2 * y + 1;
        } else {
            x--;
            err += 2 * (y - x) + 1;
        }
    }
}

/* =========================================================
 *  video_init
 * ========================================================= */
void video_init(void)
{
    gc_write(GC_MODE, 0x00);
    seq_write(SEQ_MAPMASK, 0x0F);

    video_clear(0x00);
    video_flush();
}
